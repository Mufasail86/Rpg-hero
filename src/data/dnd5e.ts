function w(
  id: string,
  name: string,
  weight: number,
  costCp: number,
  damage: string,
  attr: "str" | "dex" | "finesse",
  category: "simple" | "martial" | "unarmed",
  flags: Partial<CatalogItem["weapon"]>,
  info: string,
): CatalogItem {
  return {
    id,
    name,
    kind: "weapon",
    weight,
    costCp,
    info,
    weapon: { damage, attr, category, ...flags },
  };
}

function a(
  id: string,
  name: string,
  weight: number,
  costCp: number,
  ac: number,
  dexCap: number | null,
  category: "light" | "medium" | "heavy",
  stealth: boolean,
  info: string,
): CatalogItem {
  return {
    id,
    name,
    kind: "armor",
    weight,
    costCp,
    info,
    armor: { ac, dexCap, category, stealth, strReq: id === "chainmail" ? 13 : id === "splint" || id === "plate" ? 15 : undefined },
  };
}

function sh(id: string, name: string, weight: number, costCp: number, info: string): CatalogItem {
  return { id, name, kind: "shield", weight, costCp, info };
}

function g(id: string, name: string, weight: number, costCp: number, info: string): CatalogItem {
  return { id, name, kind: "gear", weight, costCp, info };
}

