function applyPairs(text: string, pairs: [string, string][]): string {
  let out = text;
  const ordered = [...pairs].sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of ordered) {
    const escaped = from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(`(?<![A-Za-zА-Яа-яЁё])${escaped}(?![A-Za-zА-Яа-яЁё])`, "gi");
    out = out.replace(re, (match) => {
      if (!to) return "";
      if (match[0] === match[0].toUpperCase() && match[0] !== match[0].toLowerCase()) {
        return to[0].toUpperCase() + to.slice(1);
      }
      return to;
    });
  }
  return out;
}

function stripLatinParens(text: string): string {
  return text.replace(/\s*\(([^)]*)\)/g, (full, inner: string) => {
    const lat = (inner.match(/[A-Za-z]/g) ?? []).length;
    const cyr = (inner.match(/[А-Яа-яЁё]/g) ?? []).length;
    if (/\d/.test(inner)) return full;
    if (lat >= 3 && lat >= cyr) return "";
    return full;
  });
}

function mendBrokenLines(text: string): string {
  return text.split("\n").map((line) => {
    if (!line.includes("'")) return line;
    const dice = line.match(/\d+d\d+(?:\s*[+−-]\s*\d+)?/gi) ?? [];
    const dcs = line.match(/СЛ\s*\d+/g) ?? [];
    const head = line.split("'")[0].replace(/[,.\s]+$/u, "");
    const nums = [...dice, ...dcs];
    const tail = nums.length ? ` Числа эффекта: ${nums.join(", ")}.` : "";
    return `${head}.${tail}`.replace(/\.\.+/g, ".");
  }).join("\n");
}

export function polishMonsterText(text: string): string {
  const cut = text.search(/\nЧисла сняты/);
  const body = cut < 0 ? text : text.slice(0, cut);
  const foot = cut < 0 ? "" : text.slice(cut);
  let next = stripLatinParens(body.replace(/’/g, "'"));
  next = next.replace(/(\d+)(?:st|nd|rd|th)(?![A-Za-z])/gi, "$1");
  next = next.replace(/(?<=[А-Яа-яЁё])et(?![A-Za-z])/g, "");
  next = applyPairs(next, CYRILLIC);
  next = applyPairs(next, PHRASES);
  next = applyPairs(next, LEXICON);
  next = mendBrokenLines(next);
  next = next.replace(/[ ]{2,}/g, " ").replace(/ +([,.;:])/g, "$1");
  return next + foot;
}

const ALLOWED_LATIN = new Set([
  "orc", "srd", "pdf", "cc", "by", "hp", "ac", "dc", "xp", "dr", "ft",
]);

/** Латинские слова в тексте способностей, без строки источника. */
export function disallowedLatin(text: string): string[] {
  const cut = text.search(/\nЧисла сняты/);
  const body = cut < 0 ? text : text.slice(0, cut);
  const words = body.match(/[A-Za-z]{2,}/g) ?? [];
  return words.filter((word) => !ALLOWED_LATIN.has(word.toLowerCase()));
}
