function weapon(
  id: string,
  name: string,
  weight: number,
  costCp: number,
  damage: string,
  attr: "str" | "dex" | "finesse",
  category: "simple" | "martial" | "unarmed",
  light: boolean,
  info: string,
): CatalogItem {
  return {
    id,
    name,
    kind: "weapon",
    weight,
    costCp,
    info,
    weapon: {
      damage,
      attr,
      category,
      light,
      finesse: attr === "finesse",
      ranged: id.includes("bow") || id === "crossbow",
    },
  };
}

function armor(
  id: string,
  name: string,
  weight: number,
  costCp: number,
  bonus: number,
  dexCap: number | null,
  category: "unarmored" | "light" | "medium" | "heavy",
  info: string,
): CatalogItem {
  return {
    id,
    name,
    kind: "armor",
    weight,
    costCp,
    info,
    armor: {
      bonus,
      dexCap,
      category,
      strReq: id === "scale-mail" || id === "hide" ? 14 : id === "breastplate" || id === "chainmail" ? 16 : id === "half-plate" || id === "full-plate" ? 18 : undefined,
      checkPenalty: id === "scale-mail" || id === "hide" || id === "breastplate" || id === "chainmail" ? 2 : id === "half-plate" || id === "full-plate" ? 3 : id === "leather" || id === "studded" || id === "chain-shirt" ? 1 : 0,
      speedPenalty: id === "scale-mail" || id === "hide" || id === "breastplate" || id === "chainmail" ? 5 : id === "half-plate" || id === "full-plate" ? 10 : 0,
    },
  };
}

function shield(id: string, name: string, weight: number, costCp: number, info: string): CatalogItem {
  return { id, name, kind: "shield", weight, costCp, info };
}

function gear(id: string, name: string, weight: number, costCp: number, info: string): CatalogItem {
  return { id, name, kind: "gear", weight, costCp, info };
}

